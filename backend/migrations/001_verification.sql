-- FaceVPlus: account verification + college-email-only access.
-- Run once in the Supabase SQL editor. Existing rows are marked 'approved'
-- so current users keep working; every NEW row defaults to 'pending'.

BEGIN;

-- ---------------------------------------------------------------- teachers
ALTER TABLE public.teachers
    ADD COLUMN IF NOT EXISTS email  text,
    ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'approved';

ALTER TABLE public.teachers DROP CONSTRAINT IF EXISTS teachers_status_check;
ALTER TABLE public.teachers
    ADD CONSTRAINT teachers_status_check CHECK (status IN ('pending', 'approved', 'rejected'));

ALTER TABLE public.teachers ALTER COLUMN status SET DEFAULT 'pending';
CREATE UNIQUE INDEX IF NOT EXISTS teachers_email_key ON public.teachers (email);

-- ---------------------------------------------------------------- students
ALTER TABLE public.students
    ADD COLUMN IF NOT EXISTS email   text,
    ADD COLUMN IF NOT EXISTS roll_no text,
    ADD COLUMN IF NOT EXISTS status  text NOT NULL DEFAULT 'approved';

ALTER TABLE public.students DROP CONSTRAINT IF EXISTS students_status_check;
ALTER TABLE public.students
    ADD CONSTRAINT students_status_check CHECK (status IN ('pending', 'approved', 'rejected'));

ALTER TABLE public.students ALTER COLUMN status SET DEFAULT 'pending';
CREATE UNIQUE INDEX IF NOT EXISTS students_email_key ON public.students (email);

-- Existing students keep their old numeric id as their roll number.
UPDATE public.students SET roll_no = student_id::text WHERE roll_no IS NULL;

-- College roll numbers (e.g. 24bcs086) are not numeric, so student_id is now
-- generated by the database instead of typed in by the student.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'students'
          AND column_name = 'student_id'
          AND is_identity = 'NO' AND column_default IS NULL
    ) THEN
        ALTER TABLE public.students ALTER COLUMN student_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END $$;

SELECT setval(
    pg_get_serial_sequence('public.students', 'student_id'),
    (SELECT COALESCE(MAX(student_id), 0) FROM public.students) + 1,
    false
);

-- ------------------------------------------------------- subject_students
ALTER TABLE public.subject_students
    ADD COLUMN IF NOT EXISTS status       text NOT NULL DEFAULT 'approved',
    ADD COLUMN IF NOT EXISTS requested_at timestamptz NOT NULL DEFAULT now();

ALTER TABLE public.subject_students DROP CONSTRAINT IF EXISTS subject_students_status_check;
ALTER TABLE public.subject_students
    ADD CONSTRAINT subject_students_status_check CHECK (status IN ('pending', 'approved', 'rejected'));

ALTER TABLE public.subject_students ALTER COLUMN status SET DEFAULT 'pending';

COMMIT;
