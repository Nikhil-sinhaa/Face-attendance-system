"""Repository functions for the ``students`` table."""
from typing import Any, Dict, List, Optional

from .client import get_supabase


def get_all_students() -> List[Dict[str, Any]]:
    """Return all non-rejected student records (used for face login)."""
    client = get_supabase()
    result = client.table("students").select("*").neq("status", "rejected").execute()
    return result.data or []


def get_student_by_id(student_id: int) -> Optional[Dict[str, Any]]:
    """Return the student record for ``student_id``, or None if not found."""
    client = get_supabase()
    result = (
        client.table("students")
        .select("student_id, name, email, roll_no, status, face_embedding, voice_embedding")
        .eq("student_id", student_id)
        .limit(1)
        .execute()
    )
    return result.data[0] if result.data else None


def get_student_by_email(email: str) -> Optional[Dict[str, Any]]:
    """Return the student record matching ``email`` (case-insensitive), or None."""
    client = get_supabase()
    result = (
        client.table("students")
        .select("student_id, name, email, roll_no, status")
        .eq("email", email.strip().lower())
        .limit(1)
        .execute()
    )
    return result.data[0] if result.data else None


def create_student(
    name: str,
    email: str,
    roll_no: str,
    face_embedding: Optional[List[float]] = None,
    voice_embedding: Optional[List[float]] = None,
) -> Dict[str, Any]:
    """Insert a new student in the ``pending`` state and return it.

    ``student_id`` is generated by the database.

    Raises:
        RuntimeError: If the database insert returns no data.
    """
    client = get_supabase()
    payload = {
        "name": name.strip(),
        "email": email.strip().lower(),
        "roll_no": roll_no.strip().lower(),
        "status": "pending",
        "face_embedding": face_embedding,
        "voice_embedding": voice_embedding,
    }
    result = client.table("students").insert(payload).execute()
    if not result.data:
        raise RuntimeError("Failed to register student profile.")
    return result.data[0]


def approve_student_if_pending(student_id: int) -> bool:
    """Mark a ``pending`` student as ``approved``. Returns True if a row changed."""
    client = get_supabase()
    result = (
        client.table("students")
        .update({"status": "approved"})
        .eq("student_id", student_id)
        .eq("status", "pending")
        .execute()
    )
    return bool(result.data)
